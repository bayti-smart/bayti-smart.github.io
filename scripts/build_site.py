#!/usr/bin/env python3
"""Static site generator for Smart Casa.

Input : products.json (generated by fetch_products.py) + site/ (templates, assets, content, i18n)
Output: dist/  (served by GitHub Pages)

URL scheme: English at the root (/, /p/<id>/ ...), other languages under /ar/ /fr/ /es/ /de/.
Usage: python scripts/build_site.py [--out dist]
"""
import argparse
import datetime
import hashlib
import json
import re
import shutil
import sys
from pathlib import Path

from bs4 import BeautifulSoup
from jinja2 import Environment, FileSystemLoader, select_autoescape

ROOT = Path(__file__).resolve().parent.parent
SITE = ROOT / 'site'
LANGS = ['en', 'ar', 'fr', 'es', 'de']
LANG_NAMES = [('en', 'English'), ('ar', 'العربية'), ('fr', 'Français'), ('es', 'Español'), ('de', 'Deutsch')]
OG_LOCALE = {'en': 'en_US', 'ar': 'ar_AR', 'fr': 'fr_FR', 'es': 'es_ES', 'de': 'de_DE'}
GIDS = ['bulbs', 'cameras', 'plugs', 'zigbee', 'sensors', 'garden', 'electrical']
# Mirrors the rules the old site used (first match wins)
GUIDE_RULES = [
    (r'zigbee', 'zigbee'),
    (r'camera|doorbell', 'cameras'),
    (r'bulb|lamp-holder', 'bulbs'),
    (r'plug|power-strip', 'plugs'),
    (r'din-rail|energy-meter|switch|curtain|dimmer|gigabit|breaker|boiler|relay|ups|ceiling-fan', 'electrical'),
    (r'sensor|detector|thermometer', 'sensors'),
    (r'garden|watering|soil|grow', 'garden'),
]
CAT_GUIDE = {'lighting': 'bulbs', 'security': 'cameras', 'power': 'plugs', 'control': 'electrical',
             'sensors': 'sensors', 'garden': 'garden', 'network': 'zigbee'}


def guide_for(pid):
    for rx, gid in GUIDE_RULES:
        if re.search(rx, pid):
            return gid
    return None


def trim(text, n):
    text = ' '.join((text or '').split())
    if len(text) <= n:
        return text
    return text[:n - 1].rsplit(' ', 1)[0].rstrip('.,;:،') + '…'


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--out', default='dist')
    args = ap.parse_args()
    out = ROOT / args.out
    if out.exists():
        shutil.rmtree(out)
    out.mkdir(parents=True)

    cfg = json.load(open(SITE / 'config.json', encoding='utf-8'))
    base = cfg['site_url'].rstrip('/')
    i18n = json.load(open(SITE / 'i18n.json', encoding='utf-8'))
    data = json.load(open(ROOT / 'products.json', encoding='utf-8'))
    for _p in data['products']:  # نسخة الصورة المحلية إن وُجدت (أسرع ولا تعتمد على CDN خارجي)
        if (SITE / 'assets/img/p' / (_p['id'] + '.jpg')).exists():
            _p['image'] = '/assets/img/p/' + _p['id'] + '.jpg'
    guide_titles = json.load(open(SITE / 'content/guides/titles.json', encoding='utf-8'))
    guide_index = json.load(open(SITE / 'content/guides/index.json', encoding='utf-8'))
    year = datetime.date.today().year
    ver = hashlib.sha1((SITE / 'assets/css/main.css').read_bytes() + (SITE / 'assets/js/main.js').read_bytes()).hexdigest()[:8]
    banner_json = json.dumps(i18n['banner'], ensure_ascii=False)

    env = Environment(loader=FileSystemLoader(str(SITE / 'templates')), autoescape=select_autoescape(['html']),
                      trim_blocks=True, lstrip_blocks=True)

    def prefix(lang):
        return '' if lang == 'en' else f'/{lang}'

    def path(lang, kind, arg=None):
        p = prefix(lang)
        return {
            'home': p + '/', 'products': p + '/products/', 'cat': f'{p}/c/{arg}/', 'product': f'{p}/p/{arg}/',
            'guides': p + '/guides/', 'guide': f'{p}/guides/{arg}/', 'about': p + '/about/', 'privacy': p + '/privacy/',
        }[kind]

    def absu(p):
        return base + p

    def write(url_path, html):
        target = out / url_path.lstrip('/') / 'index.html'
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(html, encoding='utf-8')

    # ---------- per-language data ----------
    cats_raw = data['categories']
    products_raw = data['products']
    cat_count = {}
    for p in products_raw:
        cat_count[p['category']] = cat_count.get(p['category'], 0) + 1

    def read(p):
        return (SITE / p).read_text(encoding='utf-8')

    def excerpt(html):
        soup = BeautifulSoup(html, 'html.parser')
        el = soup.find(['p', 'li'])
        return trim(el.get_text(' ', strip=True) if el else '', 150)

    L = {}
    for lang in LANGS:
        ui = {k: v[lang] for k, v in i18n['ui'].items()}
        cats = [{'id': c['id'], 'name': c['name'][lang], 'count': cat_count.get(c['id'], 0),
                 'intro': i18n['cat_intro'][c['id']][lang]} for c in cats_raw if cat_count.get(c['id'])]
        cname = {c['id']: c['name'] for c in cats}
        prods = []
        for p in products_raw:
            i = p['i18n'][lang]
            prods.append({'id': p['id'], 'category': p['category'], 'cat_name': cname[p['category']], 'price': p['price'],
                          'image': p['image'], 'affiliate_url': p['affiliate_url'], 'title': i['title'],
                          'description': i['description'], 'tags': i['tags']})
        guides = []
        for gid in GIDS:
            body = read(f'content/guides/{lang}/{gid}.html')
            guides.append({'id': gid, 'title': guide_titles[gid][lang], 'body': body, 'excerpt': excerpt(body)})
        pages = {}
        for pg in ('about', 'privacy'):
            pages[pg] = {'title': read(f'content/pages/{lang}/{pg}.title').strip(),
                         'body': read(f'content/pages/{lang}/{pg}.html').replace('[[guides]]', path(lang, 'guides'))}
        L[lang] = {'ui': ui, 'cats': cats, 'prods': prods, 'guides': guides, 'pages': pages}

    sitemap = []  # list of (kind, arg)

    def make_ctx(lang, kind, arg=None, **page):
        d = L[lang]

        def t(key):
            return d['ui'][key]

        def u(k, a=None):
            return path(lang, k, a)

        alt_paths = {l: path(l, kind, arg) for l in LANGS}
        ctx = {
            'lang': lang, 'dir': 'rtl' if lang == 'ar' else 'ltr', 't': t, 'u': u, 'cats': d['cats'],
            'langs': LANG_NAMES, 'alt_paths': alt_paths,
            'alternates': [(l, absu(alt_paths[l])) for l in LANGS], 'x_default': absu(alt_paths['en']),
            'canonical': absu(alt_paths[lang]), 'og_image': absu('/assets/img/og-default.png'),
            'og_locale': OG_LOCALE[lang], 'banner_json': banner_json, 'ver': ver, 'year': year,
            'social': {k: cfg.get(k, '') for k in ('facebook', 'instagram', 'tiktok')},
            'goatcounter': cfg.get('goatcounter', ''), 'jsonld': [], 'active': '',
        }
        ctx.update(page)
        return ctx

    def breadcrumb_ld(lang, items):
        return {'@context': 'https://schema.org', '@type': 'BreadcrumbList', 'itemListElement': [
            {'@type': 'ListItem', 'position': i + 1, 'name': name, **({'item': absu(href)} if href else {})}
            for i, (name, href) in enumerate(items)]}

    def render(tpl, ctx):
        return env.get_template(tpl).render(**ctx)

    for lang in LANGS:
        d = L[lang]
        t = lambda k, d=d: d['ui'][k]
        u = lambda k, a=None, lang=lang: path(lang, k, a)
        by_id = {p['id']: p for p in d['prods']}

        # ----- home -----
        latest = []
        for c in d['cats']:
            same = [p for p in d['prods'] if p['category'] == c['id']]
            if same:
                latest.append(same[-1])
        latest = latest[:8]
        org = {'@context': 'https://schema.org', '@type': 'Organization', 'name': 'Smart Casa', 'url': absu('/'),
               'logo': absu('/assets/img/favicon-256.png'), 'sameAs': [x for x in (cfg.get('facebook'), cfg.get('instagram'), cfg.get('tiktok')) if x]}
        website = {'@context': 'https://schema.org', '@type': 'WebSite', 'name': 'Smart Casa', 'url': absu(path(lang, 'home')),
                   'inLanguage': lang, 'potentialAction': {'@type': 'SearchAction',
                   'target': absu(path(lang, 'products')) + '?q={search_term_string}', 'query-input': 'required name=search_term_string'}}
        ctx = make_ctx(lang, 'home', title=t('site_title'), description=t('site_desc'), latest=latest, guides=d['guides'],
                       jsonld=[org, website], body_class='home')
        write(path(lang, 'home'), render('home.html', ctx))
        sitemap.append(('home', None))

        # ----- all products -----
        ctx = make_ctx(lang, 'products', title=f"{t('all_products')} | Smart Casa", description=t('site_desc'),
                       products=d['prods'], active='products',
                       jsonld=[breadcrumb_ld(lang, [(t('breadcrumb_home'), path(lang, 'home')), (t('all_products'), None)])])
        write(path(lang, 'products'), render('products.html', ctx))
        sitemap.append(('products', None))

        # ----- categories -----
        for c in d['cats']:
            prods = [p for p in d['prods'] if p['category'] == c['id']]
            gid = CAT_GUIDE.get(c['id'])
            guide = next((g for g in d['guides'] if g['id'] == gid), None)
            itemlist = {'@context': 'https://schema.org', '@type': 'ItemList', 'name': c['name'], 'itemListElement': [
                {'@type': 'ListItem', 'position': i + 1, 'url': absu(path(lang, 'product', p['id'])), 'name': p['title']}
                for i, p in enumerate(prods[:30])]}
            ctx = make_ctx(lang, 'cat', c['id'], title=f"{c['name']} | Smart Casa", description=trim(c['intro'], 158),
                           cat=c, products=prods, guide=guide, active='products',
                           jsonld=[breadcrumb_ld(lang, [(t('breadcrumb_home'), path(lang, 'home')), (t('nav_products'), path(lang, 'products')), (c['name'], None)]), itemlist])
            write(path(lang, 'cat', c['id']), render('category.html', ctx))
            sitemap.append(('cat', c['id']))

        # ----- products -----
        for p in d['prods']:
            gid = guide_for(p['id'])
            guide = next((g for g in d['guides'] if g['id'] == gid), None)
            related = [r for r in d['prods'] if r['category'] == p['category'] and r['id'] != p['id']][:4]
            ctx = make_ctx(lang, 'product', p['id'], title=f"{p['title']} | Smart Casa", description=trim(p['description'], 158),
                           p=p, guide=guide, related=related, og_image=(p['image'] if p['image'].startswith('http') else absu(p['image'])), og_type='article', body_class='has-sticky',
                           jsonld=[breadcrumb_ld(lang, [(t('breadcrumb_home'), path(lang, 'home')), (p['cat_name'], path(lang, 'cat', p['category'])), (p['title'], None)])])
            write(path(lang, 'product', p['id']), render('product.html', ctx))
            sitemap.append(('product', p['id']))

        # ----- guides -----
        gi = guide_index[lang]
        ctx = make_ctx(lang, 'guides', title=f"{gi['title']} | Smart Casa", description=trim(gi['intro'], 158),
                       guides=d['guides'], heading=gi['title'], intro=gi['intro'], active='guides',
                       jsonld=[breadcrumb_ld(lang, [(t('breadcrumb_home'), path(lang, 'home')), (gi['title'], None)])])
        write(path(lang, 'guides'), render('guides_index.html', ctx))
        sitemap.append(('guides', None))
        for g in d['guides']:
            gid = g['id']
            related = [p for p in d['prods'] if guide_for(p['id']) == gid][:8]
            others = [o for o in d['guides'] if o['id'] != gid]
            article = {'@context': 'https://schema.org', '@type': 'Article', 'headline': g['title'], 'inLanguage': lang,
                       'description': g['excerpt'], 'mainEntityOfPage': absu(path(lang, 'guide', gid)),
                       'author': {'@type': 'Organization', 'name': 'Smart Casa'},
                       'publisher': {'@type': 'Organization', 'name': 'Smart Casa', 'logo': {'@type': 'ImageObject', 'url': absu('/assets/img/favicon-256.png')}}}
            ctx = make_ctx(lang, 'guide', gid, title=f"{g['title']} | Smart Casa", description=trim(g['excerpt'], 158),
                           g=g, body=g['body'], products=related, others=others, active='guides', og_type='article',
                           jsonld=[breadcrumb_ld(lang, [(t('breadcrumb_home'), path(lang, 'home')), (gi['title'], path(lang, 'guides')), (g['title'], None)]), article])
            write(path(lang, 'guide', gid), render('guide.html', ctx))
            sitemap.append(('guide', gid))

        # ----- about / privacy -----
        for pg in ('about', 'privacy'):
            pgd = d['pages'][pg]
            ctx = make_ctx(lang, pg, title=f"{pgd['title']} | Smart Casa", description=trim(re.sub('<[^>]+>', ' ', pgd['body']), 158),
                           heading=pgd['title'], body=pgd['body'], active=pg if pg == 'about' else '',
                           jsonld=[breadcrumb_ld(lang, [(t('breadcrumb_home'), path(lang, 'home')), (pgd['title'], None)])])
            write(path(lang, pg), render('page.html', ctx))
            sitemap.append((pg, None))

    # sitemap holds every language's pages; collapse to unique (kind,arg)
    seen, unique = set(), []
    for k in sitemap:
        if k not in seen:
            seen.add(k)
            unique.append(k)

    # ---------- 404 ----------
    ctx = make_ctx('en', 'home', title='Page not found | Smart Casa', description=L['en']['ui']['not_found_text'], noindex=True)
    ctx['alt_paths'] = {l: path(l, 'home') for l in LANGS}
    (out / '404.html').write_text(render('notfound.html', ctx), encoding='utf-8')

    # ---------- legacy URLs (old site) -> new pages ----------
    shim = ('<!doctype html><html lang="en"><head><meta charset="utf-8"><meta name="robots" content="noindex">'
            '<meta name="google-site-verification" content="raH29vC-bBP7RB79A_HnaJtxSO3uh8426ZFTxGYd9pM">'
            '<title>Smart Casa</title><link rel="canonical" href="%(base)s%(en)s">'
            '<script>(function(){var L=["ar","en","fr","es","de"],q=new URLSearchParams(location.search).get("lang"),s=null;'
            'try{s=localStorage.getItem("sc_lang")||localStorage.getItem("site_lang")}catch(e){}'
            'var lg=L.indexOf(q)>-1?q:(L.indexOf(s)>-1?s:"en"),pre=lg==="en"?"":"/"+lg,'
            'h=(location.hash||"").replace("#","").replace(/-(ar|en|fr|es|de)$/,""),ids=%(ids)s;'
            'location.replace(pre+"%(seg)s"+(%(guide)s&&ids.indexOf(h)>-1?h+"/":""))})()</script>'
            '<noscript><meta http-equiv="refresh" content="0;url=%(en)s"></noscript></head>'
            '<body><a href="%(en)s">Smart Casa</a></body></html>')
    for fname, seg, guide in (('guides.html', '/guides/', 'true'), ('about.html', '/about/', 'false'), ('privacy.html', '/privacy/', 'false')):
        (out / fname).write_text(shim % {'base': base, 'en': seg, 'seg': seg, 'guide': guide, 'ids': json.dumps(GIDS)}, encoding='utf-8')

    # ---------- sitemaps: one file per language + an index (sitemap.xml) ----------
    head = ['<?xml version="1.0" encoding="UTF-8"?>',
            '<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9" xmlns:xhtml="http://www.w3.org/1999/xhtml">']
    for lang in LANGS:
        lines = list(head)
        for kind, arg in unique:
            lines.append(f'  <url><loc>{absu(path(lang, kind, arg))}</loc>')
            for l in LANGS:
                lines.append(f'    <xhtml:link rel="alternate" hreflang="{l}" href="{absu(path(l, kind, arg))}"/>')
            lines.append(f'    <xhtml:link rel="alternate" hreflang="x-default" href="{absu(path("en", kind, arg))}"/>')
            lines.append('  </url>')
        lines.append('</urlset>')
        (out / f'sitemap-{lang}.xml').write_text('\n'.join(lines) + '\n', encoding='utf-8')
    idx = ['<?xml version="1.0" encoding="UTF-8"?>', '<sitemapindex xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">']
    idx += [f'  <sitemap><loc>{base}/sitemap-{lang}.xml</loc></sitemap>' for lang in LANGS]
    idx.append('</sitemapindex>')
    (out / 'sitemap.xml').write_text('\n'.join(idx) + '\n', encoding='utf-8')
    (out / 'robots.txt').write_text(f'User-agent: *\nAllow: /\n\nSitemap: {base}/sitemap.xml\n', encoding='utf-8')

    # ---------- assets ----------
    shutil.copytree(SITE / 'assets', out / 'assets')
    shutil.copy(SITE / 'assets/img/favicon.ico', out / 'favicon.ico')
    shutil.copy(ROOT / 'products.json', out / 'products.json')
    n = sum(1 for _ in out.rglob('index.html'))
    print(f'built {n} pages + 404 + 3 legacy redirects + sitemap ({len(unique) * len(LANGS)} URLs) -> {out}')


if __name__ == '__main__':
    sys.exit(main())
