const LANG_ORDER = ['ar', 'en', 'fr', 'es', 'de'];

let ALL_PRODUCTS = [];
let ALL_CATEGORIES = [];
let ACTIVE_CATEGORY = 'all';
let LANG = localStorage.getItem('site_lang') || 'ar';
let LAST_UPDATED = null;

function t(key) {
  return (UI[LANG] && UI[LANG][key]) || (UI.en[key] || key);
}

/* ---------- اللغة ---------- */
function applyLanguage() {
  document.getElementById('htmlRoot').setAttribute('lang', LANG);
  document.getElementById('htmlRoot').setAttribute('dir', UI[LANG].dir);
  document.title = t('pageTitle');

  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.dataset.i18n;
    if (key === 'copyright') {
      el.innerHTML = '© <span id="year"></span> ' + t('brandName');
      document.getElementById('year').textContent = new Date().getFullYear();
    } else {
      el.textContent = t(key);
    }
  });
  document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
    el.placeholder = t(el.dataset.i18nPlaceholder);
  });
  document.querySelectorAll('[data-i18n-title]').forEach(el => {
    el.title = t(el.dataset.i18nTitle);
  });

  const select = document.getElementById('langSelect');
  if (select) select.value = LANG;

  renderCategoryLabels();
  renderStats();
  renderGrid();
  updateShareLinks();
}

function buildLangSwitch() {
  const box = document.getElementById('langSwitch');
  if (!box) return;
  const select = document.createElement('select');
  select.id = 'langSelect';
  select.className = 'lang-select';
  select.setAttribute('aria-label', 'Language / اللغة');
  LANG_ORDER.forEach(code => {
    const opt = document.createElement('option');
    opt.value = code;
    opt.textContent = `${UI[code].flag} ${code.toUpperCase()}`;
    select.appendChild(opt);
  });
  select.value = LANG;
  select.addEventListener('change', () => {
    LANG = select.value;
    localStorage.setItem('site_lang', LANG);
    applyLanguage();
  });
  box.appendChild(select);
}

/* ---------- حماية العين ---------- */
function applyEyeComfort(on) {
  document.documentElement.classList.toggle('eye-comfort', on);
  const btn = document.getElementById('eyeComfortBtn');
  if (btn) btn.classList.toggle('is-active', on);
}

function initEyeComfort() {
  const btn = document.getElementById('eyeComfortBtn');
  if (!btn) return;
  let on = localStorage.getItem('eye_comfort') === '1';
  applyEyeComfort(on);
  btn.addEventListener('click', () => {
    on = !on;
    localStorage.setItem('eye_comfort', on ? '1' : '0');
    applyEyeComfort(on);
  });
}

/* ---------- حجم الخط ---------- */
function applyFontScale(scale) {
  document.documentElement.style.setProperty('--font-scale', scale);
}

function initFontControls() {
  const dec = document.getElementById('fontDec');
  const inc = document.getElementById('fontInc');
  if (!dec || !inc) return;
  let scale = parseFloat(localStorage.getItem('font_scale') || '1');
  applyFontScale(scale);
  const save = () => { localStorage.setItem('font_scale', scale); applyFontScale(scale); };
  dec.addEventListener('click', () => { scale = Math.max(0.85, +(scale - 0.1).toFixed(2)); save(); });
  inc.addEventListener('click', () => { scale = Math.min(1.4, +(scale + 0.1).toFixed(2)); save(); });
}

/* ---------- زر العودة للأعلى ---------- */
function initBackToTop() {
  const btn = document.getElementById('backToTop');
  if (!btn) return;
  window.addEventListener('scroll', () => {
    btn.classList.toggle('is-visible', window.scrollY > 500);
  });
  btn.addEventListener('click', () => window.scrollTo({ top: 0, behavior: 'smooth' }));
}

/* ---------- المشاركة ---------- */
function updateShareLinks() {
  const shareWa = document.getElementById('shareWa');
  const shareFb = document.getElementById('shareFb');
  if (!shareWa || !shareFb) return;
  const url = location.origin + location.pathname;
  const msg = encodeURIComponent(t('shareMsg') + ' ' + url);
  shareWa.href = 'https://wa.me/?text=' + msg;
  shareFb.href = 'https://www.facebook.com/sharer/sharer.php?u=' + encodeURIComponent(url);
}

/* ---------- المنتجات ---------- */
async function loadProducts() {
  try {
    const res = await fetch('products.json?_=' + Date.now());
    const data = await res.json();
    ALL_PRODUCTS = data.products || [];
    ALL_CATEGORIES = data.categories || [];
    LAST_UPDATED = data.updated_at || null;
    renderCategoryButtons();
    applyLanguage();
  } catch (err) {
    console.error('فشل تحميل المنتجات / Failed to load products:', err);
    document.getElementById('productGrid').innerHTML =
      '<p>تعذّر تحميل المنتجات حاليًا / Could not load products right now.</p>';
  }
}

function renderStats() {
  document.getElementById('statCount').textContent = ALL_PRODUCTS.length;
  const catCountEl = document.getElementById('statCatCount');
  if (catCountEl) catCountEl.textContent = ALL_CATEGORIES.length;
  if (LAST_UPDATED) {
    const d = new Date(LAST_UPDATED);
    document.getElementById('statUpdated').textContent =
      d.toLocaleDateString(t('locale'), { year: 'numeric', month: 'short', day: 'numeric' });
  }
}

function renderCategoryButtons() {
  const nav = document.getElementById('catNav');
  nav.querySelectorAll('.cat-btn:not([data-cat="all"])').forEach(b => b.remove());
  ALL_CATEGORIES.forEach(cat => {
    const btn = document.createElement('button');
    btn.className = 'cat-btn';
    btn.dataset.cat = cat.id;
    btn.textContent = cat.name[LANG] || cat.name.en;
    btn.addEventListener('click', () => setActiveCategory(cat.id));
    nav.appendChild(btn);
  });
}

function renderCategoryLabels() {
  document.querySelectorAll('.cat-btn').forEach(btn => {
    if (btn.dataset.cat === 'all') return;
    const cat = ALL_CATEGORIES.find(c => c.id === btn.dataset.cat);
    if (cat) btn.textContent = cat.name[LANG] || cat.name.en;
  });
}

function setActiveCategory(catId) {
  ACTIVE_CATEGORY = catId;
  document.querySelectorAll('.cat-btn').forEach(b => {
    b.classList.toggle('is-active', b.dataset.cat === catId);
  });
  renderGrid();
}

function localize(product) {
  return product.i18n[LANG] || product.i18n.en || Object.values(product.i18n)[0];
}

function renderGrid() {
  const grid = document.getElementById('productGrid');
  const emptyState = document.getElementById('emptyState');
  const comingSoon = document.getElementById('comingSoon');
  if (!grid) return;

  if (ALL_PRODUCTS.length === 0) {
    grid.innerHTML = '';
    emptyState.hidden = true;
    if (comingSoon) {
      comingSoon.hidden = false;
      comingSoon.querySelector('.cs-title').textContent = t('comingSoonTitle');
      comingSoon.querySelector('.cs-body').textContent = t('comingSoonBody');
    }
    return;
  }
  if (comingSoon) comingSoon.hidden = true;

  const compatNote = document.getElementById('compatNoteBox');
  if (compatNote) {
    const hasAmazon = ALL_PRODUCTS.some(p => p.network === 'amazon');
    compatNote.hidden = !hasAmazon;
  }

  const query = document.getElementById('searchInput').value.trim().toLowerCase();

  const filtered = ALL_PRODUCTS.filter(p => {
    const text = localize(p);
    const matchesCat = ACTIVE_CATEGORY === 'all' || p.category === ACTIVE_CATEGORY;
    const matchesQuery = !query ||
      text.title.toLowerCase().includes(query) ||
      (text.description || '').toLowerCase().includes(query);
    return matchesCat && matchesQuery;
  });

  grid.innerHTML = filtered.map(renderCard).join('');
  emptyState.hidden = filtered.length > 0;
}

function renderCard(p) {
  const text = localize(p);
  const tags = (text.tags || []).map(tag => `<span class="tag">${escapeHtml(tag)}</span>`).join('');
  const stars = '★'.repeat(Math.round(p.rating || 0));
  return `
    <article class="card">
      <img class="card-img" src="${escapeHtml(p.image)}" alt="${escapeHtml(text.title)}" loading="lazy">
      <div class="card-body">
        <div class="card-tags">${tags}</div>
        <h3 class="card-title">${escapeHtml(text.title)}</h3>
        <p class="card-desc">${escapeHtml(text.description || '')}</p>
        <div class="card-meta">
          ${p.rating > 0 ? `<span class="rating"><strong>${stars}</strong> (${p.reviews_count || 0})</span>` : '<span></span>'}
          ${p.price > 0 ? `<span class="price">${p.price} <small>${p.currency || ''}</small></span>` : `<span class="price-note">${escapeHtml(t('checkPrice'))}</span>`}
        </div>
        <a class="buy-btn" href="${escapeHtml(p.affiliate_url)}" target="_blank" rel="nofollow sponsored noopener">
          ${escapeHtml(t('viewProduct'))}
        </a>
      </div>
    </article>
  `;
}

function escapeHtml(str) {
  const div = document.createElement('div');
  div.textContent = str ?? '';
  return div.innerHTML;
}

document.getElementById('searchInput')?.addEventListener('input', () => renderGrid());
document.querySelector('[data-cat="all"]')?.addEventListener('click', () => setActiveCategory('all'));
document.getElementById('copyLink')?.addEventListener('click', async (e) => {
  const btn = e.currentTarget;
  try {
    await navigator.clipboard.writeText(location.origin + location.pathname);
    btn.textContent = t('copied');
    setTimeout(() => { btn.textContent = t('copyLink'); }, 1500);
  } catch (err) { console.error(err); }
});

buildLangSwitch();
initEyeComfort();
initFontControls();
initBackToTop();
loadProducts();
